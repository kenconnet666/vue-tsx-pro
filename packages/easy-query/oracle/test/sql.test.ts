import assert from 'node:assert/strict';
import { describe, it } from 'vitest';
import { createDb } from '@zerodep-dev/easy-query-ts';
import { Gadget, Post, schema, User } from '@zerodep-dev/easy-query-ts-test/fixture';
import { oracle } from '../src/index.ts';

const pool = {} as never;

describe('oracle: SQL text', () => {
  const db = createDb({ schema, adapter: oracle(pool) });
  const old = createDb({ schema, adapter: oracle(pool, { version: '11.2' }) });

  it(':n 参数、表别名不写 AS、OFFSET … FETCH；日期时间参数写成 TO_TIMESTAMP', () => {
    const { sql, params } = db
      .queryable(User)
      .where((u) => u.createdAt.ge(new Date('2026-01-02T03:04:05.006Z')))
      .orderBy((u) => u.id)
      .offset(10)
      .limit(5)
      .select((u) => u.id)
      .toSQL();
    assert.equal(
      sql,
      `SELECT t0."id" AS "c0" FROM "t_user" t0 WHERE t0."created_at" >= TO_TIMESTAMP(:1, 'YYYY-MM-DD HH24:MI:SS.FF3') ORDER BY t0."id" ASC OFFSET 10 ROWS FETCH NEXT 5 ROWS ONLY`,
    );
    assert.deepEqual(params, ['2026-01-02 03:04:05.006']);
  });

  it('11.2：ROWNUM 包两层分页；条件当值写成 CASE WHEN（23ai 之前没有 SQL 的 BOOLEAN）', () => {
    assert.equal(
      old
        .queryable(Post)
        .orderBy((p) => p.id)
        .offset(10)
        .limit(5)
        .select((p) => p.title)
        .toSQL().sql,
      `SELECT "c0" FROM (SELECT eq_a.*, ROWNUM eq_rn FROM (SELECT t0."title" AS "c0" FROM "t_post" t0 ORDER BY t0."id" ASC) eq_a WHERE ROWNUM <= 15) WHERE eq_rn > 10 ORDER BY eq_rn`,
    );
    assert.equal(
      old
        .queryable(User)
        .select((u) => ({ adult: u.age.ge(18) }))
        .toSQL().sql,
      `SELECT CASE WHEN t0."age" >= :1 THEN 1 ELSE 0 END AS "c0" FROM "t_user" t0`,
    );
    assert.equal(
      db
        .queryable(User)
        .select((u) => ({ adult: u.age.ge(18) }))
        .toSQL().sql,
      `SELECT t0."age" >= :1 AS "c0" FROM "t_user" t0`,
    );
  });

  it('多行插入写成匿名块；upsert 写成 MERGE；经过导航的更新写成多列子查询加 EXISTS', () => {
    const [insert] = db
      .insert(Post)
      .values([
        { userId: 1, title: 'a', amount: '1.00' },
        { userId: 2, title: 'b', amount: '2.00' },
      ])
      .toSQL();
    assert.equal(
      insert!.sql,
      `BEGIN INSERT INTO "t_post" ("user_id", "title", "amount") VALUES (:1, :2, :3); INSERT INTO "t_post" ("user_id", "title", "amount") VALUES (:4, :5, :6); END;`,
    );
    assert.equal(
      db
        .update(Post)
        .set((p) => ({ title: p.user.name }))
        .where((p) => p.id.eq(1))
        .toSQL().sql,
      `UPDATE "t_post" t0_w SET ("title") = (SELECT t1."name" FROM "t_post" t0 LEFT JOIN "t_user" t1 ON t1."id" = t0."user_id" WHERE t0_w."id" = t0."id")` +
        ` WHERE EXISTS (SELECT 1 FROM "t_post" t0 LEFT JOIN "t_user" t1 ON t1."id" = t0."user_id" WHERE t0_w."id" = t0."id" AND t0."id" = :1)`,
    );
  });

  it('版本门槛：IDENTITY 要 12.1；LISTAGG(DISTINCT) 要 19', () => {
    assert.throws(
      () => old.createTableSql(Gadget),
      /IDENTITY columns needs oracle 12\.1 or later \(the dialect is configured for 11\.2\)/,
    );
    const v18 = createDb({ schema, adapter: oracle(pool, { version: '18' }) });
    assert.throws(
      () =>
        v18
          .queryable(Post)
          .groupBy((p) => ({ userId: p.userId }))
          .select((g) => ({ titles: g.joining((p) => p.title, { distinct: true }) }))
          .toSQL(),
      /LISTAGG\(DISTINCT …\) needs oracle 19 or later/,
    );
  });

  it('建表：NUMBER、VARCHAR2(n CHAR)、TIMESTAMP(3)、BOOLEAN（23ai）、DEFAULT 在 NOT NULL 前', () => {
    assert.equal(
      db.createTableSql(Gadget),
      `CREATE TABLE IF NOT EXISTS "t_gadget" ("id" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY NOT NULL, "name" VARCHAR2(50 CHAR) NOT NULL,` +
        ` "price" NUMBER(10, 2) NOT NULL, "qty" NUMBER(10) DEFAULT 0 NOT NULL, "active" BOOLEAN NOT NULL, "born" DATE, "seen_at" TIMESTAMP(3) NOT NULL,` +
        ` "tags" JSON NOT NULL, "photo" BLOB, PRIMARY KEY ("id"), UNIQUE ("name"))`,
    );
  });
});
