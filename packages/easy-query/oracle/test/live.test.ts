/**
 * 在实库上跑共用套件。EQTS_ORACLE_URL=oracle://eqts:密码@127.0.0.1:21521/FREEPDB1，未设置时跳过
 * （容器：infra/dev/db.sh --profile oracle up -d）。每个用例重建 eqts 用户下的表。
 */
import { afterAll, describe, it, vi } from 'vitest';
import oracledb from 'oracledb';
import { createDb, type Statement } from '@zerodep-dev/easy-query-ts';
import { schema, type TestEnv } from '@zerodep-dev/easy-query-ts-test/fixture';
import { liveSuite } from '@zerodep-dev/easy-query-ts-test/suite';
import { oracle, oracleSession } from '../src/index.ts';

const TABLES = [
  't_dept',
  't_doc',
  't_note',
  't_member',
  't_user_role',
  't_role',
  't_ext',
  't_comment',
  't_post',
  't_user',
  't_company',
];

const id = '"id" NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY';
const DDL = [
  `CREATE TABLE "t_company" (${id}, "name" VARCHAR2(100 CHAR) NOT NULL)`,
  `CREATE TABLE "t_user" (${id}, "name" VARCHAR2(100 CHAR) NOT NULL, "age" NUMBER(10), "company_id" NUMBER(19), "attrs" JSON NOT NULL, "created_at" TIMESTAMP(3) NOT NULL)`,
  `CREATE TABLE "t_post" (${id}, "user_id" NUMBER(19) NOT NULL, "title" VARCHAR2(200 CHAR) NOT NULL, "amount" NUMBER(12, 2) NOT NULL)`,
  `CREATE TABLE "t_comment" (${id}, "post_id" NUMBER(19) NOT NULL, "body" VARCHAR2(200 CHAR) NOT NULL)`,
  `CREATE TABLE "t_ext" (${id}, "amount" NUMBER(12, 2) NOT NULL, "big" NUMBER(19) NOT NULL, "day" DATE NOT NULL, "starts_at" TIMESTAMP(3) NOT NULL, "at" TIMESTAMP(3) NOT NULL, "clock" VARCHAR2(12) NOT NULL, "raw" BLOB NOT NULL)`,
  `CREATE TABLE "t_role" (${id}, "name" VARCHAR2(100 CHAR) NOT NULL)`,
  `CREATE TABLE "t_user_role" ("user_id" NUMBER(19) NOT NULL, "role_id" NUMBER(19) NOT NULL, PRIMARY KEY ("user_id", "role_id"))`,
  `CREATE TABLE "t_member" ("tenant_id" NUMBER(10) NOT NULL, "id" NUMBER(10) NOT NULL, "name" VARCHAR2(100 CHAR) NOT NULL, PRIMARY KEY ("tenant_id", "id"))`,
  `CREATE TABLE "t_dept" ("id" NUMBER(19) PRIMARY KEY, "parent_id" NUMBER(19), "name" VARCHAR2(100 CHAR) NOT NULL)`,
  `CREATE TABLE "t_note" (${id}, "tenant_id" NUMBER(10) NOT NULL, "member_id" NUMBER(10) NOT NULL, "body" VARCHAR2(200 CHAR) NOT NULL)`,
  `CREATE TABLE "t_doc" (${id}, "title" VARCHAR2(100 CHAR) NOT NULL, "status" VARCHAR2(20 CHAR) DEFAULT 'draft' NOT NULL, "deleted" BOOLEAN NOT NULL, "version" NUMBER(10) NOT NULL, "created_by" VARCHAR2(100 CHAR) NOT NULL, "token" VARCHAR2(100 CHAR) NOT NULL, "updated_at" TIMESTAMP(3), "secret" VARCHAR2(100 CHAR) NOT NULL)`,
];

// Oracle 的数据字典视图（USER_*）查起来慢：读库结构、建表的用例要几秒
vi.setConfig({ testTimeout: 30_000 });

const raw = process.env['EQTS_ORACLE_URL'];

if (!raw) {
  describe('oracle (live)', () => {
    it('skipped: set EQTS_ORACLE_URL to run', { skip: true }, () => {});
  });
} else {
  const url = new URL(raw);
  let pool: oracledb.Pool | undefined;
  const connect = async (): Promise<oracledb.Pool> =>
    (pool ??= await oracledb.createPool({
      user: decodeURIComponent(url.username),
      password: decodeURIComponent(url.password),
      connectString: `${url.hostname}:${url.port}${url.pathname}`,
      poolMin: 0,
      poolMax: 5,
      sessionCallback: oracleSession,
    }));
  afterAll(async () => {
    await pool?.close(0);
  });

  const open = async (): Promise<TestEnv> => {
    const p = await connect();
    const conn = await p.getConnection();
    try {
      for (const t of TABLES)
        await conn.execute(`DROP TABLE IF EXISTS "${t}" CASCADE CONSTRAINTS PURGE`);
      for (const statement of DDL) await conn.execute(statement);
    } finally {
      await conn.close();
    }
    const statements: Statement[] = [];
    const adapter = await oracle.detect(p);
    return {
      db: createDb({
        schema,
        adapter,
        log: (s) => statements.push(s),
      }),
      statements,
      adapter,
    };
  };

  liveSuite(`oracle ${url.port}`, open, {
    extensionTypes: true,
    extraTables: true,
    returning: false,
    createTableAs: false,
    // 只读事务的快照不认几乎同时新建的表（ORA-01466）：每个用例都重建表，这里测不了；功能本身照常可用
    readOnlyTransactions: false,
  });
}
