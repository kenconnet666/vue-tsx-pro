/**
 * 在实库上跑共用套件。EQTS_DB2_URL=DATABASE=eqts;HOSTNAME=127.0.0.1;PORT=25000;PROTOCOL=TCPIP;UID=db2inst1;PWD=密码，未设置时跳过
 * （容器：infra/dev/db.sh --profile db2 up -d）。ibm_db 要先装好 IBM CLI 驱动：pnpm --filter @zerodep-dev/easy-query-ts-db2 driver
 */
import { afterAll, describe, it, vi } from 'vitest';
import { createDb, type Statement } from '@zerodep-dev/easy-query-ts';
import { schema, type TestEnv } from '@zerodep-dev/easy-query-ts-test/fixture';
import { liveSuite } from '@zerodep-dev/easy-query-ts-test/suite';
import { db2 } from '../src/index.ts';

// Db2 的建表、读目录比别的库慢
vi.setConfig({ testTimeout: 30_000 });

const TABLES = [
  't_dept',
  't_doc',
  't_note',
  't_member',
  't_user_role',
  't_role',
  't_ext',
  't_comment',
  't_post',
  't_user',
  't_company',
];

const id = '"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY';
const DDL = [
  `CREATE TABLE "t_company" (${id}, "name" VARCHAR(100) NOT NULL)`,
  `CREATE TABLE "t_user" (${id}, "name" VARCHAR(100) NOT NULL, "age" INTEGER, "company_id" BIGINT, "attrs" CLOB NOT NULL, "created_at" TIMESTAMP(3) NOT NULL)`,
  `CREATE TABLE "t_post" (${id}, "user_id" BIGINT NOT NULL, "title" VARCHAR(200) NOT NULL, "amount" DECIMAL(12, 2) NOT NULL)`,
  `CREATE TABLE "t_comment" (${id}, "post_id" BIGINT NOT NULL, "body" VARCHAR(200) NOT NULL)`,
  `CREATE TABLE "t_ext" (${id}, "amount" DECIMAL(12, 2) NOT NULL, "big" BIGINT NOT NULL, "day" DATE NOT NULL, "starts_at" TIMESTAMP(3) NOT NULL, "at" TIMESTAMP(3) NOT NULL, "clock" TIME NOT NULL, "raw" BLOB NOT NULL)`,
  `CREATE TABLE "t_role" (${id}, "name" VARCHAR(100) NOT NULL)`,
  `CREATE TABLE "t_user_role" ("user_id" BIGINT NOT NULL, "role_id" BIGINT NOT NULL, PRIMARY KEY ("user_id", "role_id"))`,
  `CREATE TABLE "t_member" ("tenant_id" INTEGER NOT NULL, "id" INTEGER NOT NULL, "name" VARCHAR(100) NOT NULL, PRIMARY KEY ("tenant_id", "id"))`,
  `CREATE TABLE "t_dept" ("id" BIGINT NOT NULL PRIMARY KEY, "parent_id" BIGINT, "name" VARCHAR(100) NOT NULL)`,
  `CREATE TABLE "t_note" (${id}, "tenant_id" INTEGER NOT NULL, "member_id" INTEGER NOT NULL, "body" VARCHAR(200) NOT NULL)`,
  `CREATE TABLE "t_doc" (${id}, "title" VARCHAR(100) NOT NULL, "status" VARCHAR(20) DEFAULT 'draft' NOT NULL, "deleted" BOOLEAN NOT NULL, "version" INTEGER NOT NULL, "created_by" VARCHAR(100) NOT NULL, "token" VARCHAR(100) NOT NULL, "updated_at" TIMESTAMP(3), "secret" VARCHAR(100) NOT NULL)`,
];

const url = process.env['EQTS_DB2_URL'];

if (!url) {
  describe('db2 (live)', () => {
    it('skipped: set EQTS_DB2_URL to run', { skip: true }, () => {});
  });
} else {
  // 只在要跑时才加载 ibm_db：没装 CLI 驱动的环境（普通的测试任务）加载原生模块就会失败
  const { default: ibmdb } = await import('ibm_db');
  const pool = new ibmdb.Pool();
  afterAll(async () => {
    await pool.close();
  });

  const open = async (): Promise<TestEnv> => {
    const conn = await pool.open(url);
    try {
      for (const t of TABLES) await conn.query(`DROP TABLE IF EXISTS "${t}"`);
      for (const statement of DDL) await conn.query(statement);
    } finally {
      await conn.close();
    }
    const statements: Statement[] = [];
    const adapter = db2(pool, url);
    return {
      db: createDb({ schema, adapter, log: (s) => statements.push(s) }),
      statements,
      adapter,
    };
  };

  liveSuite(`db2 ${/PORT=(\d+)/.exec(url)?.[1] ?? ''}`, open, {
    extensionTypes: true,
    extraTables: true,
    returning: false,
    createTableAs: false,
    readOnlyTransactions: false,
    noWait: false,
    jsonLength: false,
  });
}
