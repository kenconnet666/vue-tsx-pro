import assert from 'node:assert/strict';
import { describe, it } from 'vitest';
import { createDb } from '@zerodep-dev/easy-query-ts';
import { Dept, Gadget, Post, schema } from '@zerodep-dev/easy-query-ts-test/fixture';
import { db2 } from '../src/index.ts';

const pool = {} as never;

describe('db2: SQL text', () => {
  const db = createDb({ schema, adapter: db2(pool, '') });

  it('OFFSET … FETCH 分页；upsert 写成 MERGE … USING (VALUES …)', () => {
    assert.equal(
      db
        .queryable(Post)
        .orderBy((p) => p.id)
        .offset(10)
        .limit(5)
        .select((p) => p.title)
        .toSQL().sql,
      `SELECT t0."title" AS "c0" FROM "t_post" t0 ORDER BY t0."id" ASC OFFSET 10 ROWS FETCH NEXT 5 ROWS ONLY`,
    );
    const [upsert] = db
      .insert(Post)
      .values([{ id: 1, userId: 1, title: 'a', amount: '1.00' }])
      .onConflict((p) => p.id)
      .merge((p) => [p.title])
      .toSQL();
    assert.equal(
      upsert!.sql,
      `MERGE INTO "t_post" AS eq_t USING (VALUES (?, ?, ?, ?)) AS eq_s ("id", "user_id", "title", "amount") ON eq_t."id" = eq_s."id"` +
        ` WHEN MATCHED THEN UPDATE SET "title" = eq_s."title" WHEN NOT MATCHED THEN INSERT ("id", "user_id", "title", "amount") VALUES (eq_s."id", eq_s."user_id", eq_s."title", eq_s."amount")`,
    );
  });

  it('递归 CTE 的递归成员不写带 ON 的 join（改成 CROSS JOIN，条件挪进 WHERE）', () => {
    const sql = db
      .descendantsOf(Dept, 1, { parent: (d) => d.parentId })
      .select((d) => d.name)
      .toSQL().sql;
    const recursive = sql.slice(sql.indexOf('UNION ALL'), sql.indexOf(') SELECT'));
    assert.doesNotMatch(recursive, / ON /, sql);
  });

  it('建表：IDENTITY、VARCHAR(n CODEUNITS32)、BOOLEAN、CLOB、BLOB', () => {
    assert.equal(
      db.createTableSql(Gadget),
      `CREATE TABLE IF NOT EXISTS "t_gadget" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "name" VARCHAR(50 CODEUNITS32) NOT NULL,` +
        ` "price" DECIMAL(10, 2) NOT NULL, "qty" INTEGER NOT NULL DEFAULT 0, "active" BOOLEAN NOT NULL, "born" DATE, "seen_at" TIMESTAMP(3) NOT NULL,` +
        ` "tags" CLOB NOT NULL, "photo" BLOB, PRIMARY KEY ("id"), UNIQUE ("name"))`,
    );
  });
});
