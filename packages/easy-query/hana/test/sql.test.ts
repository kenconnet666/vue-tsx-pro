import assert from 'node:assert/strict';
import { describe, it } from 'vitest';
import { createDb, greatest } from '@zerodep-dev/easy-query-ts';
import {
  Company,
  ddlSchema,
  Gadget,
  Post,
  schema,
  User,
} from '@zerodep-dev/easy-query-ts-test/fixture';
import { hana } from '../src/index.ts';

describe('hana: SQL text', () => {
  // 只渲染，不连库（连接池在第一次执行时才连）
  const db = createDb({
    schema,
    adapter: hana({ host: 'unused', port: 0, user: 'x', password: 'x' }),
  });

  it('writes multi-row inserts as SELECT … FROM DUMMY UNION ALL', () => {
    const [s] = db
      .insert(Post)
      .values([
        { userId: 1, title: 'a', amount: '1' },
        { userId: 2, title: 'b', amount: '2' },
      ])
      .toSQL();
    assert.equal(
      s!.sql,
      'INSERT INTO "t_post" ("user_id", "title", "amount") SELECT ? AS "user_id", ? AS "title", ? AS "amount" FROM DUMMY' +
        ' UNION ALL SELECT ? AS "user_id", ? AS "title", ? AS "amount" FROM DUMMY',
    );
    assert.deepEqual(s!.params, ['1', 'a', '1', '2', 'b', '2']);
  });

  it('writes upserts as MERGE', () => {
    const [merge] = db
      .insert(Company)
      .values({ id: 1, name: 'x' })
      .onConflict((c) => c.id)
      .merge()
      .toSQL();
    assert.equal(
      merge!.sql,
      'MERGE INTO "t_company" eq_t USING (SELECT ? AS "id", ? AS "name" FROM DUMMY) eq_s ON (eq_t."id" = eq_s."id")' +
        ' WHEN MATCHED THEN UPDATE SET eq_t."name" = eq_s."name" WHEN NOT MATCHED THEN INSERT ("id", "name") VALUES (eq_s."id", eq_s."name")',
    );
    const [ignore] = db
      .insert(Company)
      .values({ id: 1, name: 'x' })
      .onConflict((c) => c.id)
      .ignore()
      .toSQL();
    assert.ok(!ignore!.sql.includes('WHEN MATCHED'));
  });

  it('needs a LIMIT before OFFSET', () => {
    assert.match(db.queryable(Post).offset(3).toSQL().sql, / LIMIT 2147483647 OFFSET 3$/);
  });
});

describe('hana: code-first DDL', () => {
  const db = createDb({
    schema,
    adapter: hana({ host: 'unused', port: 0, user: 'x', password: 'x' }),
  });

  it('renders CREATE COLUMN TABLE with HANA types (no IF NOT EXISTS)', () => {
    assert.equal(
      db.createTableSql(Gadget),
      'CREATE COLUMN TABLE "t_gadget" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "name" NVARCHAR(50) NOT NULL, "price" DECIMAL(10, 2) NOT NULL,' +
        ' "qty" INTEGER NOT NULL DEFAULT 0, "active" BOOLEAN NOT NULL, "born" DATE, "seen_at" TIMESTAMP NOT NULL, "tags" NCLOB NOT NULL, "photo" BLOB, PRIMARY KEY ("id"), UNIQUE ("name"))',
    );
  });

  it('renders the function library in HANA syntax', () => {
    const { sql, params } = db
      .queryable(User)
      .select((u) => ({
        text: u.createdAt.format('yyyy-MM-dd HH:mm'),
        later: u.createdAt.addHours(2),
        hours: u.createdAt.diff(u.createdAt.addDays(1), 'hour'),
        dow: u.createdAt.dayOfWeek(),
        hi: greatest(u.age, 20),
        cut: u.age.truncate(1),
        titles: u.posts.joining((p) => p.title, { separator: '|' }),
      }))
      .toSQL();
    for (const part of [
      `TO_VARCHAR(t0."created_at", 'YYYY-MM-DD HH24:MI')`,
      `ADD_SECONDS(t0."created_at", (2) * 3600)`,
      `CAST(SECONDS_BETWEEN(ADD_DAYS(t0."created_at", 1), t0."created_at") / 3600 AS BIGINT)`,
      `MOD(WEEKDAY(t0."created_at") + 1, 7)`,
      `GREATEST(COALESCE(t0."age", ?), COALESCE(?, t0."age"))`,
      `ROUND(t0."age", 1, ROUND_DOWN)`,
      `STRING_AGG(TO_VARCHAR(t1."title"), '|')`,
    ])
      assert.ok(sql.includes(part), `missing ${part} in ${sql}`);
    // 重复出现的参数各绑一次，顺序与文字一致
    assert.deepEqual(params, ['20', '20']);
  });
});

describe('hana: create statements with comments, indexes and foreign keys', async () => {
  const db = createDb({
    schema: ddlSchema,
    adapter: hana({ host: 'unused', port: 0, user: 'x', password: 'x' }),
  });

  it('renders every statement in order', () => {
    assert.deepEqual(db.createTablesSql(), [
      'CREATE COLUMN TABLE "t_shelf" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "name" NVARCHAR(50) NOT NULL, PRIMARY KEY ("id"))',
      'CREATE COLUMN TABLE "t_book" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "shelf_id" BIGINT NOT NULL, "title" NVARCHAR(100) NOT NULL, PRIMARY KEY ("id"))',
      'COMMENT ON TABLE "t_shelf" IS \'书架\'',
      'COMMENT ON COLUMN "t_shelf"."name" IS \'书架\'\'s 名\'',
      'CREATE UNIQUE INDEX "t_book_shelf_id_title_uidx" ON "t_book" ("shelf_id", "title")',
      'ALTER TABLE "t_book" ADD CONSTRAINT "fk_t_book_shelf_id" FOREIGN KEY ("shelf_id") REFERENCES "t_shelf" ("id") ON DELETE CASCADE',
    ]);
  });

  it('renames and adds columns in HANA syntax', () => {
    const { dialect } = hana({ host: 'unused', port: 0, user: 'x', password: 'x' });
    assert.equal(
      dialect.renameColumn('t_book', 'title', 'name'),
      'RENAME COLUMN "t_book"."title" TO "name"',
    );
    assert.equal(dialect.renameTable('t_book', 't_books'), 'RENAME TABLE "t_book" TO "t_books"');
    assert.equal(
      dialect.addColumn('t_book', 'note', 'string', {
        nullable: true,
        primaryKey: false,
        generated: false,
        hasDefault: false,
        length: 20,
      }),
      'ALTER TABLE "t_book" ADD ("note" NVARCHAR(20))',
    );
    assert.equal(dialect.dropTable('t_book'), 'DROP TABLE "t_book"');
  });
});
