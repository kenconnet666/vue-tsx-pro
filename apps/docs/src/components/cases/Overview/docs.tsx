/** 一张简单的表：第一列是行标题 */
function simpleTable(
  label: string,
  head: readonly string[],
  rows: readonly (readonly VNodeChild[])[],
) {
  return (
    <Table aria-label={label} density="compact">
      <TableHead>
        <TableRow>
          {head.map((cell) => (
            <TableHeaderCell key={cell}>{cell}</TableHeaderCell>
          ))}
        </TableRow>
      </TableHead>
      <TableBody>
        {rows.map((row, index) => (
          <TableRow key={index}>
            {row.map((cell, column) =>
              column === 0 ? (
                <TableHeaderCell key={column} scope="row">
                  {cell}
                </TableHeaderCell>
              ) : (
                <TableCell key={column}>{cell}</TableCell>
              ),
            )}
          </TableRow>
        ))}
      </TableBody>
    </Table>
  );
}

